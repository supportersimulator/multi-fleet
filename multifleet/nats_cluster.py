"""
NATS Cluster Configuration — resilient multi-server fleet comms.

Each fleet node runs its own nats-server. Servers cluster together so
if any node goes down, remaining nodes still communicate. Clients
connect to ALL known servers for automatic failover.

Generates nats-server.conf from .multifleet/config.json.
No hardcoded IPs — all derived from the fleet config.

Usage:
    python3 -m multifleet.nats_cluster generate   # write nats-server.conf
    python3 -m multifleet.nats_cluster start       # start clustered nats-server
    python3 -m multifleet.nats_cluster client-urls  # print client connection URLs
"""

import json
import logging
import os
import signal
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import Optional

logger = logging.getLogger("fleet.nats-cluster")

REPO_ROOT = Path(os.environ.get("MULTIFLEET_REPO_ROOT", str(Path(__file__).parent.parent)))
CONFIG_PATH = REPO_ROOT / ".multifleet" / "config.json"
CONF_DIR = REPO_ROOT / ".multifleet" / "nats"
CONF_FILE = CONF_DIR / "nats-server.conf"
PID_FILE = CONF_DIR / "nats-server.pid"

# Ports
CLIENT_PORT = 4222       # Client connections
CLUSTER_PORT = 6222      # Inter-server cluster routes
MONITOR_PORT = 8222      # HTTP monitoring

# JetStream
JETSTREAM_STORE = CONF_DIR / "jetstream"


def _load_config() -> dict:
    """Load fleet config."""
    if not CONFIG_PATH.exists():
        return {}
    return json.loads(CONFIG_PATH.read_text())


def _get_local_ip() -> str:
    """Get LAN IP."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return "127.0.0.1"


def _detect_node_id(cfg: dict) -> str:
    """Detect which node we are from config."""
    env_id = os.environ.get("MULTIFLEET_NODE_ID")
    if env_id:
        return env_id
    my_ip = _get_local_ip()
    for nid, node in cfg.get("nodes", {}).items():
        if node.get("host") == my_ip:
            return nid
    return socket.gethostname().split(".")[0].lower()


def generate_config(node_id: Optional[str] = None) -> str:
    """Generate nats-server.conf for this node with cluster routes to all peers.

    Returns the config file content as a string.
    """
    cfg = _load_config()
    if not cfg:
        return _minimal_config()

    if not node_id:
        node_id = _detect_node_id(cfg)

    nodes = cfg.get("nodes", {})
    my_node = nodes.get(node_id, {})
    my_ip = my_node.get("host") or _get_local_ip()
    is_chief = my_node.get("role") == "chief"

    # Build cluster routes to all OTHER nodes
    routes = []
    for nid, node in nodes.items():
        if nid == node_id:
            continue
        host = node.get("host", "")
        if host:
            routes.append(f"    nats-route://{host}:{CLUSTER_PORT}")

    routes_block = "\n".join(routes)

    # Token auth (optional)
    nats_token = os.environ.get("NATS_TOKEN", "")
    if not nats_token:
        nats_token = cfg.get("protocol", {}).get("natsToken", "")
    auth_block = ""
    if nats_token:
        auth_block = f'\n  authorization {{\n    token: "{nats_token}"\n  }}'

    # JetStream (chief gets file storage, workers get memory)
    js_store = str(JETSTREAM_STORE)
    js_storage = "file" if is_chief else "file"
    js_max = "1GB" if is_chief else "256MB"

    config = f"""# Auto-generated by multifleet.nats_cluster — do not edit manually
# Node: {node_id} ({my_ip}) | Role: {"chief" if is_chief else "worker"}
# Generated: {time.strftime("%Y-%m-%d %H:%M:%S")}

server_name: {node_id}

# Client connections
listen: 0.0.0.0:{CLIENT_PORT}
{auth_block}

# Cluster
cluster {{
  name: contextdna-fleet
  listen: 0.0.0.0:{CLUSTER_PORT}

  routes = [
{routes_block}
  ]

  # Auto-discover new routes from connected peers
  connect_retries: 120
}}

# JetStream — persistent messaging for offline nodes
jetstream {{
  store_dir: "{js_store}"
  max_memory_store: {js_max}
  max_file_store: {js_max}
}}

# HTTP monitoring
http_port: {MONITOR_PORT}

# Logging
log_file: "/tmp/nats-cluster-{node_id}.log"
logfile_size_limit: 10485760
debug: false
trace: false

# Limits
max_payload: 1048576
max_connections: 1024
ping_interval: "20s"
ping_max: 3
write_deadline: "10s"
"""
    return config


def _minimal_config() -> str:
    """Fallback config when no fleet config exists — standalone server."""
    return f"""# Standalone NATS server (no fleet config found)
listen: 0.0.0.0:{CLIENT_PORT}
jetstream {{
  store_dir: "{JETSTREAM_STORE}"
  max_memory_store: 256MB
  max_file_store: 256MB
}}
http_port: {MONITOR_PORT}
log_file: "/tmp/nats-standalone.log"
"""


def write_config(node_id: Optional[str] = None) -> Path:
    """Generate and write nats-server.conf. Returns path to config file."""
    CONF_DIR.mkdir(parents=True, exist_ok=True)
    content = generate_config(node_id)
    CONF_FILE.write_text(content)
    logger.info("Wrote NATS cluster config to %s", CONF_FILE)
    return CONF_FILE


def client_urls(include_self: bool = True) -> list[str]:
    """Return NATS client URLs for all fleet nodes.

    Used by FleetNerveNATS to connect with failover — if one
    server is down, the client automatically connects to another.
    """
    cfg = _load_config()
    if not cfg:
        return [f"nats://127.0.0.1:{CLIENT_PORT}"]

    urls = []
    node_id = _detect_node_id(cfg)

    for nid, node in cfg.get("nodes", {}).items():
        host = node.get("host", "")
        if not host:
            continue
        if nid == node_id:
            # Connect to local server via loopback (faster, no NAT issues)
            if include_self:
                urls.insert(0, f"nats://127.0.0.1:{CLIENT_PORT}")
        else:
            urls.append(f"nats://{host}:{CLIENT_PORT}")

    return urls or [f"nats://127.0.0.1:{CLIENT_PORT}"]


def start_server(node_id: Optional[str] = None, foreground: bool = False) -> Optional[int]:
    """Start nats-server with cluster config.

    Args:
        node_id: Override node detection.
        foreground: If True, blocks until server exits. If False, daemonizes.

    Returns:
        PID of started server, or None if already running.
    """
    # Check if already running
    if PID_FILE.exists():
        try:
            pid = int(PID_FILE.read_text().strip())
            os.kill(pid, 0)  # Check if process exists
            logger.info("NATS server already running (PID %d)", pid)
            return None
        except (OSError, ValueError):
            PID_FILE.unlink(missing_ok=True)

    # Generate fresh config
    conf_path = write_config(node_id)

    # Ensure JetStream store exists
    JETSTREAM_STORE.mkdir(parents=True, exist_ok=True)

    nats_bin = _find_nats_server()
    if not nats_bin:
        logger.error("nats-server not found. Install: brew install nats-server")
        return None

    cmd = [nats_bin, "-c", str(conf_path)]
    if not foreground:
        cmd.extend(["-P", str(PID_FILE)])

    logger.info("Starting NATS cluster server: %s", " ".join(cmd))

    if foreground:
        proc = subprocess.Popen(cmd)
        PID_FILE.write_text(str(proc.pid))
        try:
            proc.wait()
        except KeyboardInterrupt:
            proc.send_signal(signal.SIGTERM)
            proc.wait(timeout=10)
        finally:
            PID_FILE.unlink(missing_ok=True)
        return proc.pid
    else:
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        # Wait briefly for startup
        time.sleep(0.5)
        if proc.poll() is not None:
            logger.error("NATS server failed to start (exit code %d)", proc.returncode)
            return None
        PID_FILE.write_text(str(proc.pid))
        logger.info("NATS cluster server started (PID %d)", proc.pid)
        return proc.pid


def stop_server() -> bool:
    """Stop the nats-server started by start_server."""
    if not PID_FILE.exists():
        logger.info("No PID file — server not managed by us")
        return False
    try:
        pid = int(PID_FILE.read_text().strip())
        os.kill(pid, signal.SIGTERM)
        # Wait for graceful shutdown
        for _ in range(20):
            try:
                os.kill(pid, 0)
                time.sleep(0.25)
            except OSError:
                break
        PID_FILE.unlink(missing_ok=True)
        logger.info("NATS server stopped (PID %d)", pid)
        return True
    except (OSError, ValueError) as e:
        logger.warning("Failed to stop NATS server: %s", e)
        PID_FILE.unlink(missing_ok=True)
        return False


def server_status() -> dict:
    """Check NATS server status via monitoring endpoint."""
    import urllib.request
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{MONITOR_PORT}/varz", timeout=3) as r:
            varz = json.loads(r.read())
        with urllib.request.urlopen(f"http://127.0.0.1:{MONITOR_PORT}/routez", timeout=3) as r:
            routez = json.loads(r.read())
        return {
            "running": True,
            "server_name": varz.get("server_name", ""),
            "version": varz.get("version", ""),
            "cluster": varz.get("cluster", {}),
            "jetstream": varz.get("jetstream", {}),
            "connections": varz.get("connections", 0),
            "routes": routez.get("num_routes", 0),
            "route_details": [
                {"remote_id": r.get("remote_id", ""), "ip": r.get("ip", ""), "port": r.get("port", 0)}
                for r in routez.get("routes", [])
            ],
        }
    except Exception:
        return {"running": False}


def _find_nats_server() -> Optional[str]:
    """Find nats-server binary."""
    try:
        result = subprocess.run(["which", "nats-server"], capture_output=True, text=True)
        if result.returncode == 0:
            return result.stdout.strip()
    except Exception:
        pass
    # Common locations
    for path in ["/usr/local/bin/nats-server", "/opt/homebrew/bin/nats-server"]:
        if os.path.isfile(path):
            return path
    return None


# ── CLI ──

def main():
    import argparse
    parser = argparse.ArgumentParser(description="NATS Cluster Manager")
    parser.add_argument("command", choices=["generate", "start", "stop", "status", "client-urls", "restart"])
    parser.add_argument("--node-id", help="Override node ID")
    parser.add_argument("--foreground", action="store_true", help="Run in foreground (start only)")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")

    if args.command == "generate":
        path = write_config(args.node_id)
        print(f"Config written to {path}")
        print(generate_config(args.node_id))

    elif args.command == "start":
        pid = start_server(args.node_id, foreground=args.foreground)
        if pid:
            print(f"NATS cluster server started (PID {pid})")
        else:
            print("Server already running or failed to start")

    elif args.command == "stop":
        if stop_server():
            print("NATS server stopped")
        else:
            print("No managed server to stop")

    elif args.command == "restart":
        stop_server()
        time.sleep(1)
        pid = start_server(args.node_id)
        if pid:
            print(f"NATS cluster server restarted (PID {pid})")

    elif args.command == "status":
        s = server_status()
        if s["running"]:
            print(f"NATS server: {s['server_name']} v{s['version']}")
            print(f"Connections: {s['connections']}")
            print(f"Cluster routes: {s['routes']}")
            for r in s.get("route_details", []):
                print(f"  → {r['ip']}:{r['port']} (id: {r['remote_id'][:8]}...)")
            js = s.get("jetstream", {})
            if js:
                print(f"JetStream: {js.get('config', {}).get('store_dir', 'n/a')}")
        else:
            print("NATS server: not running")

    elif args.command == "client-urls":
        urls = client_urls()
        for url in urls:
            print(url)


if __name__ == "__main__":
    main()
